/*
 * Cloud-Tests dashboard for the "Unity Checks" workflow.
 * Reads GitHub Actions runs/jobs and the live status comments that Tests/CI/progress.py writes
 * into the issue labelled "cloud-status". Other comments there are notes from Claude.
 *
 * Embedding:  CloudDashboard.mount(element, { owner, repo, workflow, token })
 * Without a token option the dashboard asks for one and keeps it in localStorage.
 */
(function () {
  "use strict";

  const DEFAULTS = {
    owner: "LordHeronymus",
    repo: "Mining-Game",
    workflow: "unity-checks.yml",
    statusLabel: "cloud-status",
    storageKey: "cloudDashboard.v1",
    activeInterval: 5000,
    idleInterval: 30000,
  };

  const STEP_NAMES = {
    "Set up job": "Runner starten",
    "Check licence secrets": "Lizenz-Secrets prüfen",
    "Free disk space": "Speicher freiräumen",
    "Start live status": "Live-Status starten",
    "List LFS objects": "LFS-Dateien auflisten",
    "Restore LFS cache": "LFS-Cache laden",
    "Pull LFS files (Assets only)": "LFS-Dateien laden",
    "Restore Library cache": "Library-Cache laden",
    "Prepare checks": "Checks vorbereiten",
    "Run Unity": "Unity ausführen",
    "Report": "Bericht",
    "Final live status": "Live-Status abschliessen",
    "Upload artifacts": "Artefakte hochladen",
    "Save Library cache": "Library-Cache speichern",
    "Complete job": "Abschluss",
  };

  const PHASES = [
    ["prepare", "Vorbereitung"],
    ["license", "Lizenz"],
    ["unity", "Unity startet"],
    ["import", "Import"],
    ["compile", "Kompilieren"],
    ["checks", "Checks"],
    ["done", "Fertig"],
  ];

  const STATUS_TEXT = {
    queued: "Wartet", in_progress: "Läuft", waiting: "Wartet", pending: "Wartet", requested: "Angefordert",
    success: "Bestanden", failure: "Fehlgeschlagen", cancelled: "Abgebrochen", skipped: "Übersprungen",
    timed_out: "Zeitüberschreitung", action_required: "Aktion nötig", neutral: "Neutral", startup_failure: "Startfehler",
  };

  const EVENT_TEXT = { workflow_dispatch: "manuell", pull_request: "Pull Request", push: "Push", schedule: "Zeitplan" };

  function esc(value) {
    return String(value ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  }

  function storage(key, value) {
    try {
      if (value === undefined) return JSON.parse(localStorage.getItem(key) || "null");
      if (value === null) localStorage.removeItem(key);
      else localStorage.setItem(key, JSON.stringify(value));
    } catch (_) { /* storage blocked: settings live for this page load only */ }
    return null;
  }

  function duration(ms) {
    if (!(ms >= 0)) return "–";
    const s = Math.round(ms / 1000);
    const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
    if (h) return `${h} h ${String(m).padStart(2, "0")} min`;
    if (m) return `${m} min ${String(r).padStart(2, "0")} s`;
    return `${r} s`;
  }

  function clock(ms) {
    const s = Math.max(0, Math.floor(ms / 1000));
    const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
    return (h ? h + ":" + String(m).padStart(2, "0") : String(m)) + ":" + String(r).padStart(2, "0");
  }

  function ago(iso) {
    if (!iso) return "";
    const s = Math.round((Date.now() - new Date(iso).getTime()) / 1000);
    if (s < 60) return `vor ${Math.max(s, 0)} s`;
    if (s < 3600) return `vor ${Math.round(s / 60)} min`;
    if (s < 86400) return `vor ${Math.round(s / 3600)} h`;
    return new Date(iso).toLocaleDateString("de-CH");
  }

  function when(iso) {
    return iso ? new Date(iso).toLocaleString("de-CH", { dateStyle: "short", timeStyle: "short" }) : "–";
  }

  function stateOf(item) {
    return item.status === "completed" ? (item.conclusion || "neutral") : item.status;
  }

  function decodeStatus(body) {
    const run = /<!-- cloud-status run=(\d+) -->/.exec(body || "");
    if (!run) return null;
    const data = /<!-- cloud-status-data ([A-Za-z0-9+/=]+) -->/.exec(body);
    if (!data) return { run_id: Number(run[1]) };
    try {
      const bytes = Uint8Array.from(atob(data[1]), c => c.charCodeAt(0));
      return JSON.parse(new TextDecoder().decode(bytes));
    } catch (_) {
      return { run_id: Number(run[1]) };
    }
  }

  function stripFooter(text) {
    return String(text || "").replace(/\n*---\s*\n_Generated by \[Claude Code\]\([^)]*\)_\s*$/, "").trim();
  }

  function mount(root, options) {
    const opts = Object.assign({}, DEFAULTS, options || {});
    const saved = storage(opts.storageKey) || {};
    const config = {
      owner: opts.owner || saved.owner,
      repo: opts.repo || saved.repo,
      token: opts.token || saved.token || "",
    };
    if (saved.owner && !options?.owner) config.owner = saved.owner;
    if (saved.repo && !options?.repo) config.repo = saved.repo;

    const state = {
      runs: [], jobs: {}, statuses: {}, notes: [], issue: null, branches: null,
      selected: saved.selected || null, follow: saved.follow !== false,
      error: null, rateRemaining: null, lastRefresh: null, view: config.token ? "runs" : "settings",
      openResults: new Set(), logPinned: true, busy: false, message: null,
    };
    const etags = new Map();
    let timer = null, ticker = null, destroyed = false;

    root.classList.add("cd");
    root.innerHTML = `
      <header class="cd-header">
        <div class="cd-brand"><h1>Cloud-Tests</h1><span class="repo" data-ref="repo"></span></div>
        <div class="spacer"></div>
        <div class="cd-conn" data-ref="conn"><span class="cd-dot"></span><span>Nicht verbunden</span></div>
        <button class="cd-btn" type="button" data-act="start-view">Lauf starten</button>
        <button class="cd-btn" type="button" data-act="settings">Einstellungen</button>
      </header>
      <div class="cd-body">
        <nav class="cd-runs-col" aria-label="Läufe">
          <p class="cd-label">Läufe</p>
          <label class="cd-check" style="margin-bottom:8px"><input type="checkbox" id="cd-follow" data-ref="follow"> Neuesten Lauf folgen</label>
          <div class="cd-runs" data-ref="runs"></div>
        </nav>
        <main class="cd-main" data-ref="main"></main>
      </div>`;
    const $ = ref => root.querySelector(`[data-ref="${ref}"]`);
    $("follow").checked = state.follow;

    function persist() {
      if (options?.token) return;
      storage(opts.storageKey, { owner: config.owner, repo: config.repo, token: config.token, selected: state.selected, follow: state.follow });
    }

    async function gh(path, init) {
      const url = path.startsWith("http") ? path : `https://api.github.com${path}`;
      const method = (init && init.method) || "GET";
      const headers = { Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28", Authorization: `Bearer ${config.token}` };
      const cached = method === "GET" ? etags.get(url) : null;
      if (cached) headers["If-None-Match"] = cached.etag;
      const response = await fetch(url, Object.assign({ cache: "no-store" }, init, { headers: Object.assign(headers, init && init.headers) }));
      const remaining = response.headers.get("x-ratelimit-remaining");
      if (remaining !== null) state.rateRemaining = Number(remaining);
      if (response.status === 304 && cached) return cached.data;
      if (!response.ok) {
        let detail = "";
        try { detail = (await response.json()).message || ""; } catch (_) { /* no body */ }
        const error = new Error(`${response.status} ${detail}`.trim());
        error.status = response.status;
        throw error;
      }
      if (response.status === 204) return null;
      const data = await response.json();
      const etag = response.headers.get("etag");
      if (method === "GET" && etag) etags.set(url, { etag, data });
      return data;
    }

    const repoPath = () => `/repos/${encodeURIComponent(config.owner)}/${encodeURIComponent(config.repo)}`;

    async function refresh() {
      if (destroyed || !config.token) return;
      try {
        const runs = await gh(`${repoPath()}/actions/workflows/${encodeURIComponent(opts.workflow)}/runs?per_page=20`);
        state.runs = runs.workflow_runs || [];
        const newest = state.runs[0];
        if (newest && (state.follow || !state.selected || !state.runs.some(r => r.id === state.selected))) state.selected = newest.id;
        const selected = state.runs.find(r => r.id === state.selected);
        if (selected) {
          const jobs = await gh(`${repoPath()}/actions/runs/${selected.id}/jobs?per_page=50`);
          state.jobs[selected.id] = jobs.jobs || [];
        }
        await refreshComments();
        state.error = null;
        state.lastRefresh = new Date();
      } catch (error) {
        state.error = error.status === 401 ? "Der Zugangsschlüssel ist ungültig oder abgelaufen."
          : error.status === 404 ? "Repository oder Workflow nicht gefunden. Stimmen Besitzer, Repository und Schlüssel-Rechte (Actions: Read)?"
          : error.status === 403 ? `Zugriff verweigert (${error.message}). Fehlen Rechte, oder ist das API-Limit erreicht?`
          : `Abfrage fehlgeschlagen: ${error.message}`;
      }
      persist();
      render();
      schedule();
    }

    async function refreshComments() {
      try {
        if (!state.issue) {
          const issues = await gh(`${repoPath()}/issues?labels=${encodeURIComponent(opts.statusLabel)}&state=all&per_page=1`);
          state.issue = issues[0] ? issues[0].number : null;
        }
        if (!state.issue) return;
        const comments = await gh(`${repoPath()}/issues/comments?sort=updated&direction=desc&per_page=100`);
        const suffix = `/issues/${state.issue}`;
        const notes = [];
        for (const comment of comments) {
          if (!comment.issue_url.endsWith(suffix)) continue;
          const status = decodeStatus(comment.body);
          if (status) {
            const known = state.statuses[status.run_id];
            if (!known || !known.updated || !status.updated || status.updated >= known.updated) state.statuses[status.run_id] = status;
          } else {
            notes.push({ id: comment.id, at: comment.created_at, text: stripFooter(comment.body), url: comment.html_url });
          }
        }
        notes.sort((a, b) => b.at.localeCompare(a.at));
        state.notes = notes;
      } catch (error) {
        if (error.status === 403 || error.status === 404) state.notesError = "Notizen und Live-Status brauchen das Recht „Issues: Read“.";
        else throw error;
      }
    }

    function schedule() {
      clearTimeout(timer);
      if (destroyed) return;
      const active = state.runs.some(r => r.status !== "completed");
      timer = setTimeout(refresh, active ? opts.activeInterval : opts.idleInterval);
    }

    // ---------- Rendering ----------

    function render() {
      $("repo").textContent = `${config.owner}/${config.repo}`;
      renderConn();
      renderRuns();
      if (state.view === "settings") renderSettings();
      else if (state.view === "start") renderStart();
      else renderRun();
    }

    function renderConn() {
      const active = state.runs.some(r => r.status !== "completed");
      const dot = !config.token ? "" : state.error ? "bad" : active ? "live" : "ok";
      const text = !config.token ? "Kein Schlüssel" : state.error ? "Fehler"
        : `${active ? "Live" : "Verbunden"} · ${state.lastRefresh ? state.lastRefresh.toLocaleTimeString("de-CH") : "…"}`
          + (state.rateRemaining !== null ? ` · ${state.rateRemaining} Abfragen frei` : "");
      $("conn").innerHTML = `<span class="cd-dot ${dot}"></span><span>${esc(text)}</span>`;
    }

    function renderRuns() {
      const list = $("runs");
      if (!state.runs.length) {
        list.innerHTML = `<p class="cd-empty">${config.token ? "Noch keine Läufe." : "Zuerst einen Zugangsschlüssel eintragen."}</p>`;
        return;
      }
      list.innerHTML = state.runs.map(run => {
        const st = stateOf(run);
        const end = run.status === "completed" ? new Date(run.updated_at) : new Date();
        const took = duration(end - new Date(run.run_started_at || run.created_at));
        return `<button type="button" class="cd-run" data-run="${run.id}" aria-current="${run.id === state.selected}">
          <span class="cd-st ${esc(st)}" title="${esc(STATUS_TEXT[st] || st)}"></span>
          <span class="title">#${run.run_number} · ${esc(run.head_branch)}</span>
          <span class="time num">${esc(took)}</span>
          <span class="meta">${esc(EVENT_TEXT[run.event] || run.event)} · ${esc(ago(run.created_at))}</span>
        </button>`;
      }).join("");
    }

    function renderRun() {
      const main = $("main");
      const run = state.runs.find(r => r.id === state.selected);
      const banner = state.error ? `<div class="cd-banner">${esc(state.error)}</div>` : "";
      if (!run) {
        main.innerHTML = banner + `<section class="cd-panel"><p class="cd-empty">${state.runs.length ? "Lauf auswählen." : "Sobald ein Lauf existiert, erscheint er hier."}</p></section>`;
        return;
      }
      const jobs = state.jobs[run.id] || [];
      const job = jobs[0];
      const status = state.statuses[run.id];
      const st = stateOf(run);
      const started = new Date(run.run_started_at || run.created_at);
      const running = run.status !== "completed";

      // Keep log scroll and open result rows across re-renders.
      const oldLog = main.querySelector(".cd-log");
      if (oldLog) state.logPinned = oldLog.scrollHeight - oldLog.scrollTop - oldLog.clientHeight < 30;

      main.innerHTML = banner + `
        <section class="cd-panel">
          <div class="cd-runhead">
            <h2>Unity Checks #${run.run_number}</h2>
            <span class="cd-pill ${esc(st)}"><span class="cd-st ${esc(st)}"></span>${esc(STATUS_TEXT[st] || st)}</span>
            <span class="elapsed num" data-ref="elapsed" data-start="${started.getTime()}" data-end="${running ? "" : new Date(run.updated_at).getTime()}">${clock((running ? Date.now() : new Date(run.updated_at)) - started)}</span>
          </div>
          <div class="cd-facts">
            <span>Branch <b>${esc(run.head_branch)}</b></span>
            <span>Auslöser <b>${esc(EVENT_TEXT[run.event] || run.event)}</b></span>
            ${status && status.suite ? `<span>Auswahl <b>${esc(status.suite)}</b></span>` : ""}
            <span>Gestartet <b>${esc(when(run.run_started_at || run.created_at))}</b></span>
            <span>Commit <b class="num">${esc(run.head_sha.slice(0, 7))}</b></span>
          </div>
          <div class="cd-actions">
            <a class="cd-btn" href="${esc(run.html_url)}" target="_blank" rel="noopener">Auf GitHub öffnen</a>
            ${running ? `<button type="button" class="cd-btn danger" data-act="cancel" data-run="${run.id}">Abbrechen</button>` : ""}
            ${!running ? `<button type="button" class="cd-btn" data-act="rerun" data-run="${run.id}">Erneut ausführen</button>` : ""}
          </div>
          ${state.message ? `<p class="muted" style="margin:10px 0 0">${esc(state.message)}</p>` : ""}
        </section>
        ${pipeline(job)}
        ${unity(run, status)}
        <div class="cd-row">
          ${checks(status)}
          ${notes(run)}
        </div>
        ${logPanel(status)}`;

      const log = main.querySelector(".cd-log");
      if (log && state.logPinned) log.scrollTop = log.scrollHeight;
      main.querySelectorAll(".cd-result").forEach(details => {
        details.addEventListener("toggle", () => {
          if (details.open) state.openResults.add(details.dataset.name); else state.openResults.delete(details.dataset.name);
        });
      });
    }

    function pipeline(job) {
      if (!job) return `<section class="cd-panel"><p class="cd-label">Ablauf</p><p class="cd-empty">Der Lauf wartet auf einen Runner.</p></section>`;
      const steps = [];
      let cleanup = null;
      for (const step of job.steps || []) {
        if (step.name.startsWith("Post ")) {
          cleanup = cleanup || { name: "Aufräumen", status: step.status, conclusion: step.conclusion, started_at: step.started_at, completed_at: step.completed_at };
          cleanup.completed_at = step.completed_at || cleanup.completed_at;
          if (step.status !== "completed") cleanup.status = step.status;
          continue;
        }
        steps.push(step);
      }
      if (cleanup) steps.splice(steps.length - (steps.at(-1)?.name === "Complete job" ? 1 : 0), 0, cleanup);
      const now = Date.now();
      const spans = steps.map(step => {
        const start = step.started_at ? new Date(step.started_at).getTime() : null;
        const end = step.completed_at ? new Date(step.completed_at).getTime() : step.status === "in_progress" ? now : null;
        return start && end ? Math.max(end - start, 0) : 0;
      });
      const total = spans.reduce((a, b) => a + b, 0) || 1;
      const segs = steps.map((step, i) => {
        const st = stateOf(step);
        return `<span class="cd-seg ${esc(st)}" style="flex:${Math.max(spans[i] / total, 0.004)}" title="${esc(STEP_NAMES[step.name] || step.name)}: ${esc(duration(spans[i]))}"></span>`;
      }).join("");
      const items = steps.map((step, i) => {
        const st = stateOf(step);
        const name = step.name.startsWith("Run actions/checkout") ? "Repo auschecken" : STEP_NAMES[step.name] || step.name;
        return `<li class="${step.status === "in_progress" ? "current" : ""}"><span class="cd-st ${esc(st)}"></span><span class="name" title="${esc(step.name)}">${esc(name)}</span><span class="dur num">${spans[i] ? esc(duration(spans[i])) : ""}</span></li>`;
      }).join("");
      return `<section class="cd-panel"><p class="cd-label">Ablauf auf GitHub</p><div class="cd-timeline">${segs}</div><ul class="cd-steps">${items}</ul></section>`;
    }

    function unity(run, status) {
      if (!status) {
        const text = !state.issue && !state.notesError ? "Für diesen Lauf gibt es keinen Live-Status (ältere Läufe hatten noch keinen)."
          : state.notesError || "Noch kein Live-Status für diesen Lauf.";
        return `<section class="cd-panel"><p class="cd-label">Unity</p><p class="cd-empty">${esc(text)}</p></section>`;
      }
      const failedEarly = run.status === "completed" && run.conclusion !== "success";
      const current = PHASES.findIndex(([key]) => key === status.phase);
      const phases = PHASES.map(([key, label], i) => {
        let cls = i < current ? "done" : i === current ? (key === "done" ? (failedEarly ? "bad" : "done") : failedEarly ? "bad" : "now") : "";
        return `<div class="cd-phase ${cls}">${esc(label)}</div>`;
      }).join("");
      const showImport = status.imported > 0 && status.assets > 0 && ["import", "compile", "unity"].includes(status.phase);
      const pct = showImport ? Math.min(100, Math.round(status.imported / status.assets * 100)) : 0;
      const importBar = showImport ? `<div class="cd-progress"><span class="num">${status.imported.toLocaleString("de-CH")}</span> <span class="muted">von etwa ${status.assets.toLocaleString("de-CH")} Assets importiert</span><div class="cd-bar"><span style="width:${pct}%"></span></div></div>` : "";
      const errors = status.compile_errors && status.compile_errors.length ? `<pre class="cd-errors">${esc(status.compile_errors.join("\n"))}</pre>` : "";
      const fresh = run.status !== "completed" && status.updated ? `<span class="muted" style="font-size:13px"> · Status ${esc(ago(status.updated))}</span>` : "";
      return `<section class="cd-panel"><p class="cd-label">Unity · ${esc(status.phase_text || "")}${fresh}</p>
        <div class="cd-phases">${phases}</div>${importBar}${errors}</section>`;
    }

    function checks(status) {
      const rows = status && status.checks && status.checks.length ? status.checks : null;
      if (!rows) return `<section class="cd-panel"><p class="cd-label">Checks</p><p class="cd-empty">Die Auswahl erscheint, sobald der Lauf die Checks vorbereitet hat.</p></section>`;
      const passed = rows.filter(r => r.status === "PASS").length;
      const failed = rows.filter(r => r.status === "FAIL").length;
      const table = rows.map(row => `<tr>
          <td><span class="cd-chip ${esc(row.status)}">${esc({ pending: "offen", running: "läuft", PASS: "PASS", FAIL: "FAIL" }[row.status] || row.status)}</span></td>
          <td>${esc(row.name)}<div class="msg">${esc(row.message || "")}</div></td>
          <td class="muted">${esc(row.mode)}</td>
          <td class="num muted">${row.seconds != null ? esc(row.seconds.toFixed(1)) + " s" : ""}</td>
        </tr>`).join("");
      const results = status.results && status.results.length ? `<div style="margin-top:14px">${status.results.map(r => `
          <details class="cd-result" data-name="${esc(r.name)}" ${state.openResults.has(r.name) ? "open" : ""}>
            <summary><span class="cd-chip ${esc(r.status)}">${esc(r.status)}</span><span class="name">${esc(r.name)}</span><span class="num muted">${esc((r.seconds || 0).toFixed(1))} s</span></summary>
            <pre>${esc(r.output || "(keine Ausgabe)")}${r.logErrors && r.logErrors.length ? "\n\nFehler im Log:\n" + esc(r.logErrors.join("\n")) : ""}</pre>
          </details>`).join("")}</div>` : "";
      return `<section class="cd-panel"><p class="cd-label">Checks · ${passed} bestanden${failed ? ` · ${failed} fehlgeschlagen` : ""} · ${rows.length} total</p>
        <div class="cd-table-wrap"><table class="cd-table"><thead><tr><th>Status</th><th>Check</th><th>Modus</th><th>Zeit</th></tr></thead><tbody>${table}</tbody></table></div>${results}</section>`;
    }

    function notes(run) {
      const relevant = state.notes.filter(n => n.text.includes(`#${run.run_number}`) || n.text.includes(String(run.id)));
      const general = state.notes.filter(n => !relevant.includes(n)).slice(0, 3);
      const list = relevant.length ? relevant : general;
      const heading = relevant.length ? `Notizen von Claude zu #${run.run_number}` : "Letzte Notizen von Claude";
      const body = state.notesError ? `<p class="cd-empty">${esc(state.notesError)}</p>`
        : list.length ? `<div class="cd-notes">${list.map(n => `<div class="cd-note"><div class="when">${esc(when(n.at))} · <a href="${esc(n.url)}" target="_blank" rel="noopener">auf GitHub</a></div><div class="text">${esc(n.text)}</div></div>`).join("")}</div>`
        : `<p class="cd-empty">Noch keine Notizen. Claude schreibt hier, was bei einem Lauf passiert ist und was behoben wird.</p>`;
      return `<section class="cd-panel"><p class="cd-label">${esc(heading)}</p>${body}</section>`;
    }

    function logPanel(status) {
      const lines = status && status.log_tail && status.log_tail.length ? status.log_tail : null;
      if (!lines) return `<section class="cd-panel"><p class="cd-label">Unity-Log</p><p class="cd-empty">Das Log erscheint, sobald Unity läuft.</p></section>`;
      const html = lines.map(line => {
        const cls = /error|exception|fail/i.test(line) ? "err" : line.startsWith("[CI]") ? "ci" : "";
        return cls ? `<span class="${cls}">${esc(line)}</span>` : esc(line);
      }).join("\n");
      return `<section class="cd-panel"><p class="cd-label">Unity-Log · letzte ${lines.length} Zeilen</p><pre class="cd-log">${html}</pre></section>`;
    }

    function renderSettings() {
      $("main").innerHTML = `
        <section class="cd-panel">
          <p class="cd-label">Einstellungen</p>
          <form class="cd-form" data-ref="settings-form">
            <div class="cd-inline">
              <div class="cd-field"><label for="cd-owner">Besitzer</label><input id="cd-owner" name="owner" value="${esc(config.owner)}" autocomplete="off"></div>
              <div class="cd-field"><label for="cd-repo">Repository</label><input id="cd-repo" name="repo" value="${esc(config.repo)}" autocomplete="off"></div>
            </div>
            <div class="cd-field">
              <label for="cd-token">GitHub-Zugangsschlüssel</label>
              <input id="cd-token" name="token" type="password" value="${esc(config.token)}" autocomplete="off" placeholder="github_pat_…">
              <span class="hint">Bleibt nur in diesem Browser gespeichert und geht ausschliesslich an api.github.com.</span>
            </div>
            <ol class="cd-help">
              <li>Auf GitHub: <a href="https://github.com/settings/personal-access-tokens/new" target="_blank" rel="noopener">Settings → Developer settings → Fine-grained tokens → Generate new token</a>.</li>
              <li>Repository access: <b>Only select repositories</b> → ${esc(config.repo)}.</li>
              <li>Permissions: <b>Actions: Read and write</b> (Read genügt zum Zuschauen; Write für Starten/Abbrechen) und <b>Issues: Read</b>.</li>
              <li>Schlüssel kopieren, hier einfügen und speichern.</li>
            </ol>
            <div class="cd-actions">
              <button class="cd-btn primary" type="submit">Speichern und verbinden</button>
              ${config.token ? `<button class="cd-btn" type="button" data-act="back">Zurück</button><button class="cd-btn danger" type="button" data-act="forget">Schlüssel entfernen</button>` : ""}
            </div>
          </form>
        </section>`;
      $("settings-form").addEventListener("submit", event => {
        event.preventDefault();
        const form = new FormData(event.target);
        config.owner = String(form.get("owner") || "").trim() || DEFAULTS.owner;
        config.repo = String(form.get("repo") || "").trim() || DEFAULTS.repo;
        config.token = String(form.get("token") || "").trim();
        state.issue = null; state.runs = []; state.statuses = {}; state.notes = []; state.notesError = null; etags.clear();
        state.view = "runs";
        persist();
        render();
        refresh();
      });
    }

    async function renderStart() {
      const main = $("main");
      main.innerHTML = `
        <section class="cd-panel">
          <p class="cd-label">Lauf starten</p>
          <form class="cd-form" data-ref="start-form">
            <div class="cd-inline">
              <div class="cd-field"><label for="cd-branch">Branch</label><select id="cd-branch" name="ref"><option>main</option></select></div>
              <div class="cd-field"><label for="cd-suite">Suite</label><select id="cd-suite" name="suite"><option value="smoke">smoke · schnelle Edit-Mode-Checks</option><option value="play">play · Play-Mode ab MainMenu</option></select></div>
            </div>
            <div class="cd-field">
              <label for="cd-checks">Einzelne Checks (optional, ersetzt die Suite)</label>
              <input id="cd-checks" name="checks" placeholder="z. B. CaveGenerationChecks, play:GpsUiChecks" autocomplete="off">
            </div>
            <label class="cd-check"><input type="checkbox" id="cd-nographics" name="nographics"> Ohne Grafik (schneller, nur Logik-Checks)</label>
            <div class="cd-actions">
              <button class="cd-btn primary" type="submit">Starten</button>
              <button class="cd-btn" type="button" data-act="back">Zurück</button>
            </div>
            <p class="cd-empty" data-ref="start-msg"></p>
          </form>
        </section>`;
      $("start-form").addEventListener("submit", async event => {
        event.preventDefault();
        const form = new FormData(event.target);
        const inputs = { suite: String(form.get("suite")), checks: String(form.get("checks") || "").trim(), nographics: form.get("nographics") ? "true" : "false" };
        $("start-msg").textContent = "Wird gestartet …";
        try {
          await gh(`${repoPath()}/actions/workflows/${encodeURIComponent(opts.workflow)}/dispatches`, { method: "POST", body: JSON.stringify({ ref: String(form.get("ref")), inputs }) });
          state.view = "runs"; state.follow = true; $("follow").checked = true;
          state.message = "Lauf gestartet. Er erscheint in wenigen Sekunden in der Liste.";
          render();
          setTimeout(refresh, 3000);
        } catch (error) {
          $("start-msg").textContent = error.status === 403 || error.status === 404
            ? "Starten nicht erlaubt: Der Schlüssel braucht „Actions: Read and write“."
            : `Starten fehlgeschlagen: ${error.message}`;
        }
      });
      try {
        if (!state.branches) state.branches = (await gh(`${repoPath()}/branches?per_page=100`)).map(b => b.name);
        const select = root.querySelector("#cd-branch");
        if (select && state.branches.length) {
          select.innerHTML = state.branches.map(name => `<option ${name === "main" ? "selected" : ""}>${esc(name)}</option>`).join("");
        }
      } catch (_) { /* keep "main" */ }
    }

    // ---------- Events ----------

    root.addEventListener("click", async event => {
      const target = event.target.closest("[data-run],[data-act]");
      if (!target || !root.contains(target)) return;
      const act = target.dataset.act;
      if (!act && target.dataset.run) {
        state.selected = Number(target.dataset.run);
        state.follow = state.runs[0] && state.runs[0].id === state.selected ? state.follow : false;
        $("follow").checked = state.follow;
        state.view = "runs"; state.message = null; state.logPinned = true;
        render();
        refresh();
        return;
      }
      if (act === "settings") { state.view = "settings"; render(); }
      else if (act === "start-view") { state.view = config.token ? "start" : "settings"; render(); }
      else if (act === "back") { state.view = "runs"; render(); }
      else if (act === "forget") {
        config.token = ""; state.runs = []; state.statuses = {}; state.notes = []; etags.clear(); persist(); state.view = "settings"; render();
      } else if (act === "cancel" || act === "rerun") {
        target.disabled = true;
        try {
          await gh(`${repoPath()}/actions/runs/${target.dataset.run}/${act === "cancel" ? "cancel" : "rerun"}`, { method: "POST" });
          state.message = act === "cancel" ? "Abbruch angefordert." : "Lauf wird erneut ausgeführt.";
        } catch (error) {
          state.message = error.status === 403 ? "Nicht erlaubt: Der Schlüssel braucht „Actions: Read and write“." : `Fehlgeschlagen: ${error.message}`;
        }
        render();
        setTimeout(refresh, 2000);
      }
    });

    $("follow").addEventListener("change", event => {
      state.follow = event.target.checked;
      if (state.follow && state.runs[0]) state.selected = state.runs[0].id;
      persist();
      render();
    });

    // Live clock for the selected run without hitting the API.
    ticker = setInterval(() => {
      const el = root.querySelector('[data-ref="elapsed"]');
      if (el && !el.dataset.end) el.textContent = clock(Date.now() - Number(el.dataset.start));
    }, 1000);

    render();
    refresh();

    return {
      refresh,
      destroy() {
        destroyed = true;
        clearTimeout(timer);
        clearInterval(ticker);
        root.innerHTML = "";
        root.classList.remove("cd");
      },
    };
  }

  window.CloudDashboard = { mount };
})();
